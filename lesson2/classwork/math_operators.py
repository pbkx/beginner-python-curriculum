print(4 + 5)  # Addition: adds two numbers

print(10 - 3)  # Subtraction: subtracts the second number from the first number

print(5 * 4)  # Multiplication: multiplies two numbers

print(15 / 2)  # Division: divides and gives you a float result

print(15 // 2)  # Floor Divsion: divides and rounds down to whole number

print(15 % 2)  # Modulus: gives the remainder

print(2 ** 3)  # Exponentiation: first number raised to the power of second number

# You can combine numbers and math operators
# Python follows the order of operations
print(2 + 3 * 4)  # prints 14 (3 * 4 = 12, then 2 + 12)
print((2 + 3) * 4)  # prints 20 (2 + 3 = 5, then 5 * 4)

# You can use variables in your operations like numbers
a = 8
b = 3
print(a + b)
print(a * b)

# This also works with multiple artguments
x = 12
y = 5
print("The quotient is:", x // y)
print("Remainder:", x % y)